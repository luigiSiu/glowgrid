/*
 * One column of a character's bitmap.
 * Out-of-range characters render blank, so unsupported input degrades to
 * spaces rather than to noise.
 */
inline uint8_t fontColumn(char c, uint8_t column) {
  if (column >= FONT_WIDTH) {
    return 0;                       // the gap between characters
  }
  if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) {
    return 0;
  }
  return FONT5X7[c - FONT_FIRST_CHAR][column];
}
